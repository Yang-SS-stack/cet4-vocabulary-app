    expect(calls[0].animation.cancel).toHaveBeenCalledOnce()
    expect(screen.getByRole('button', { name: '学习助手' })).toHaveFocus()
    act(() => vi.advanceTimersByTime(180))
    expect(screen.queryByText('学习助手提示')).not.toBeInTheDocument()
